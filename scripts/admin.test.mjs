test('rascunho invisível, início, anulação auditável e encerramento bloqueiam novos lances',()=>{
 const data=memory();let now=100000,role='admin';const authorize=r=>{if(role!==r)throw Error('Permissão negada');return{id:'user1',name:'Ana',role};};
 const store=createAuctionStore(data,()=>now,authorize),lot=store.create({name:'Teste',collection:'151',collectionId:'sv03.5',image,opening:1000,increment:100,endsAt:500000,draft:true});
 assert.ok(!store.list().find(l=>l.id===lot.id));role='user';assert.throws(()=>store.bid(lot.id,{amount:1000}),/não foi iniciado/);
 role='admin';store.start(lot.id,500000);role='user';const bid=store.bid(lot.id,{amount:1000}).bids[0];
 role='admin';store.moderateBid(lot.id,bid.id,'Lance inválido');assert.equal(store.adminList().find(l=>l.id===lot.id).moderation[0].bid.id,bid.id);
 role='user';now+=100;store.bid(lot.id,{amount:1000});role='admin';now+=100;store.close(lot.id,'Encerramento antecipado');
 assert.equal(store.adminList().find(l=>l.id===lot.id).bids.length,1);role='user';assert.throws(()=>store.bid(lot.id,{amount:1100}),/encerrado/);
});
